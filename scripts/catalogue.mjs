// Writes the catalogue table into README.md (between the markers) and docs/reference/catalogue.md.
// npm run catalogue rewrites both; the check gate fails when either is stale.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { loadEntries, ROOT, isMain } from "./entries.mjs";
import { SITE_URL } from "./site.mjs";

const START = "<!-- catalogue:start -->";
const END = "<!-- catalogue:end -->";
const README = join(ROOT, "README.md");
const REF = join(ROOT, "docs/reference/catalogue.md");

function credit(m) {
  if (m.relation === "original") return "";
  const s = m.source;
  const label = { port: "Port of", recreation: "Recreation of", "inspired-by": "Inspired by" }[m.relation];
  return `${label} [${s.author}](${s.url})`;
}

export function table(linkBase) {
  const rows = loadEntries().filter((e) => e.meta).map((e) => {
    const m = e.meta;
    return `| [${m.name}](${SITE_URL}/${e.rel}/) | ${m.kind} | ${m.summary.replace(/\|/g, "\\|")} | ${m.tech.join(", ")} | ${credit(m)} | [code](${linkBase}${e.rel}/) |`;
  });
  return ["| Entry | Kind | What it does | Tech | Credit | Source |", "|---|---|---|---|---|---|", ...rows].join("\n");
}

function readmeWith(t) {
  const readme = readFileSync(README, "utf8");
  const a = readme.indexOf(START), b = readme.indexOf(END);
  if (a < 0 || b < 0) throw new Error("README.md is missing the catalogue markers");
  return readme.slice(0, a + START.length) + "\n\n" + t + "\n\n" + readme.slice(b);
}

function refDoc(t) {
  return `# Catalogue

Every entry in the collection, generated from each entry's \`meta.json\` by \`npm run catalogue\`. Do not edit this file by hand.

${t}
`;
}

export function catalogueIsFresh() {
  if (!existsSync(README) || !existsSync(REF)) return false;
  return readFileSync(README, "utf8") === readmeWith(table("")) && readFileSync(REF, "utf8") === refDoc(table("../../"));
}

if (isMain(import.meta.url)) {
  writeFileSync(README, readmeWith(table("")));
  writeFileSync(REF, refDoc(table("../../")));
  console.log("catalogue written");
}
